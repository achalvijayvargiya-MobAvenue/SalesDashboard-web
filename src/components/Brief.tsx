import ReactMarkdown from "react-markdown";
import remarkGfm from "remark-gfm";
import type { BriefView } from "../types";
import { Callout } from "./widgets";

export function BriefPanel({
  brief, error, busy, auto, onGenerate,
}: {
  brief: BriefView | null;
  error: string | null;
  busy: boolean;
  auto: boolean;
  onGenerate: () => void;
}) {
  return (
    <section>
      <h2>Sales brief</h2>
      {busy && !brief ? <p className="note">Researching the company on the web for the sales brief... this can take a minute.</p> : null}
      {error ? <Callout level="error" text={error} /> : null}
      {!brief && !busy && error ? <button type="button" className="primary" onClick={onGenerate}>Retry sales brief</button> : null}
      {!brief && !busy && !error && !auto ? <button type="button" className="primary" onClick={onGenerate}>Generate sales brief</button> : null}
      {brief ? (
        <>
          <p className="note">{brief.caption}</p>
          <button type="button" onClick={onGenerate} disabled={busy}>{busy ? "Regenerating…" : "Regenerate"}</button>
          {brief.highlight ? (
            <Callout level={brief.highlight.below_required ? "warning" : "success"} text={brief.highlight.text} strong />
          ) : null}
          <div className="brief">
            <ReactMarkdown remarkPlugins={[remarkGfm]} components={{
              a: ({ href, children }) => <a href={href} target="_blank" rel="noreferrer">{children}</a>,
            }}>{brief.body_markdown}</ReactMarkdown>
          </div>
          {brief.missing_inputs ? (
            <Callout level="warning" text="This brief was generated by an older version without the calculated pricing inputs. Regenerate it before quoting its payout figures." />
          ) : null}
          <button type="button" onClick={() => download(`sales-brief-${brief.bundle_id}.md`, brief.download_markdown)}>
            Download brief (.md)
          </button>
        </>
      ) : null}
    </section>
  );
}

function download(name: string, text: string) {
  const blob = new Blob([text], { type: "text/markdown" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = name;
  link.click();
  URL.revokeObjectURL(url);
}
